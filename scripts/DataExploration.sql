/* This is the table for measurement exploration' */

SELECT 'Total Sales' as measure_name, 
SUM(sales_amount) as measure_value FROM gold.fact_sales
UNION ALL
SELECT 'Total Quantity Sold' as measure_name,
SUM(quantity) AS total_quantity FROM gold.fact_sales
UNION ALL
SELECT 'Total average price' as measure_name,
AVG(price) as avg_price FROM gold.fact_sales
UNION ALL
SELECT 'Total number of orders' as measure_name,
COUNT(DISTINCT order_number) as total_orders FROM gold.fact_sales
UNION ALL
SELECT 'Total number of products' as measure_name,
COUNT(DISTINCT product_name) as total_products FROM gold.dim_products
UNION ALL
SELECT 'Total customers' as measure_name,
COUNT(customer_key) as total_customers FROM gold.dim_customers
UNION ALL
SELECT 'Customers who ordered' as measure_name,
COUNT(DISTINCT customer_key) as total_customers FROM gold.fact_sales;

/* These are the sql queries for magnitude exploration' */
-- Find total customers by countries
SELECT
country,
COUNT(DISTINCT customer_key) as total_customers
FROM gold.dim_customers
GROUP BY country
ORDER BY total_customers DESC

-- Find total customers by gender
SELECT
gender,
COUNT(DISTINCT customer_key) as total_customers
FROM gold.dim_customers
GROUP BY gender
ORDER BY total_customers DESC

-- Find total products by category
SELECT
category,
COUNT(product_id) as total_products
FROM gold.dim_products
GROUP BY category
ORDER BY total_products DESC

-- What is the average costs in each category?
SELECT
category,
AVG(cost) as average_cost
FROM gold.dim_products
GROUP BY category
ORDER BY average_cost DESC

-- What is the total revenue generated for each category?
SELECT
pr.category,
SUM(sales_amount) as total_revenue
FROM gold.fact_sales fs
LEFT JOIN gold.dim_products pr
ON fs.product_key = pr.product_key
GROUP BY category
ORDER BY total_revenue DESC

-- Find total revenue is generated by each customer.
SELECT
cu.customer_key,
cu.first_name,
cu.last_name,
SUM(sales_amount) as total_revenue
FROM gold.fact_sales fs
LEFT JOIN gold.dim_customers cu
ON fs.customer_key = cu.customer_key
GROUP BY cu.customer_key, first_name, last_name
ORDER BY total_revenue DESC

-- What is the distribution of sold items across countries?
SELECT
cu.country,
SUM(quantity) as items_sold
FROM gold.fact_sales fs
LEFT JOIN gold.dim_customers cu
ON fs.customer_key = cu.customer_key
GROUP BY country
ORDER BY items_sold DESC

/* These are the sql queries for ranking exploration' */

--Which 5 products generate the highest revenue?
SELECT TOP 5
fs.product_key,
product_name,
SUM(sales_amount) as total_revenue
FROM gold.fact_sales fs
LEFT JOIN gold.dim_products pr
ON fs.product_key = pr.product_key
GROUP BY fs.product_key, product_name
ORDER BY total_revenue DESC

--Using window function
SELECT *
FROM ( SELECT
	pr.product_name,
	SUM(sales_amount) as total_revenue,
	RoW_NUMBER() OVER (ORDER BY SUM(sales_amount) DESC) as rank_sales
	FROM gold.fact_sales fs
	LEFT JOIN gold.dim_products pr
	ON fs.product_key = pr.product_key
	GROUP BY pr.product_name) t
WHERE rank_sales <= 5


--What are the 5 worst-performing products in terms of sales?
SELECT TOP 5
fs.product_key,
product_name,
SUM(sales_amount) as total_revenue
FROM gold.fact_sales fs
LEFT JOIN gold.dim_products pr
ON fs.product_key = pr.product_key
GROUP BY fs.product_key, product_name
ORDER BY total_revenue

--Find the Top-10 customers who have generated the highest revenue
SELECT TOP 10
cu.customer_id,
cu.first_name,
cu.last_name,
SUM(fs.sales_amount) as total_revenue
FROM gold.fact_sales fs
LEFT JOIN gold.dim_customers cu
ON fs.customer_key = cu.customer_key
GROUP BY customer_id, first_name, last_name
ORDER BY total_revenue DESC

--Using window function
SELECT *
FROM
	(SELECT
	cu.customer_id,
	cu.first_name,
	cu.last_name,
	SUM(fs.sales_amount) as total_revenue,
	ROW_NUMBER() OVER (ORDER BY SUM(fs.sales_amount) DESC) as customer_rank
	FROM gold.fact_sales fs
	LEFT JOIN gold.dim_customers cu
	ON fs.customer_key = cu.customer_key
	GROUP BY customer_id, first_name, last_name)t
WHERE customer_rank <= 10

